import argparse
import contextlib
import errno
import fcntl
import os
from pathlib import Path
import re
import shlex
import shutil
import signal
import socket
import subprocess
import sys


class WorkspaceError(Exception):
    pass


def run(*args, cwd=None, capture=False, check=True, env=None):
    return subprocess.run(
        [str(arg) for arg in args], cwd=cwd, check=check, text=True,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None, env=env,
    )


class Workspaces:
    def __init__(self):
        self.repo = Path(os.environ.get("ABOARD_REPO", "~/code/aboard")).expanduser().resolve()
        self.root = self.repo / "worktrees"
        self.slot_count = int(os.environ.get("ABOARD_WT_SLOT_COUNT", "10"))
        self.reserved_slots = {3}  # The accounts app owns port 3003, even when stopped.

    def git(self, *args, check=True):
        return run("git", "-C", self.repo, *args, capture=True, check=check)

    def worktrees(self):
        records = self.git("worktree", "list", "--porcelain", "-z").stdout.split("\0\0")
        result = {}
        for record in records:
            fields = dict(line.partition(" ")[::2] for line in record.split("\0") if line)
            if "worktree" in fields:
                result[Path(fields["worktree"]).resolve()] = fields
        return result

    def branches(self):
        output = self.git("for-each-ref", "--format=%(refname) %(symref)",
                          "refs/heads", "refs/remotes").stdout
        return sorted({line.split()[0].removeprefix("refs/heads/").removeprefix("refs/remotes/")
                       for line in output.splitlines() if len(line.split()) == 1})

    def names(self):
        return sorted(path.name for path in self.worktrees()
                      if path.parent == self.root and self.managed(path))

    def path(self, name):
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,47}", name):
            raise WorkspaceError("Use a workspace name of 1–48 lowercase letters, digits, or hyphens.")
        return self.root / name

    def existing(self, name):
        path = self.path(name)
        if path not in self.worktrees() or not self.managed(path):
            raise WorkspaceError(f"Not a managed workspace: {name}")
        slot = self.config_slot(path)
        if slot is None or not 1 <= slot <= self.slot_count or slot in self.reserved_slots:
            raise WorkspaceError(f"Invalid or reserved slot in {path / 'devenv.local.nix'}")
        return path

    @contextlib.contextmanager
    def lock(self, name="allocation"):
        common = Path(self.git("rev-parse", "--path-format=absolute", "--git-common-dir").stdout.strip())
        with (common / f"aboard-wt-{name}.lock").open("w") as handle:
            try:
                fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                raise WorkspaceError(f"Another aboard-wt operation is using {name}; try again shortly.") from None
            yield

    @staticmethod
    def config_slot(path):
        config = path / "devenv.local.nix"
        if not config.is_file():
            return None
        match = re.search(r'^\s*PORT = (?:lib\.mkForce )?"([0-9]+)";', config.read_text(), re.MULTILINE)
        return int(match[1]) - 3000 if match else None

    @staticmethod
    def managed(path):
        config = path / "devenv.local.nix"
        return config.is_file() and config.read_text().startswith("# Generated by aboard-wt.")

    @staticmethod
    def port_busy(port):
        for family, host in ((socket.AF_INET, "127.0.0.1"), (socket.AF_INET6, "::1")):
            try:
                with socket.socket(family) as sock:
                    sock.bind((host, port))
            except OSError as error:
                if family == socket.AF_INET6 and error.errno in (errno.EAFNOSUPPORT, errno.EADDRNOTAVAIL):
                    continue
                return True
        return False

    def allocate_slot(self):
        used = {self.config_slot(path) for path in self.worktrees()}
        for slot in range(1, self.slot_count + 1):
            if slot not in used | self.reserved_slots and not any(
                self.port_busy(port) for port in (3000 + slot, 6379 + slot)
            ):
                return slot
        raise WorkspaceError("No free nginx worktree slots. Remove an unused workspace or increase the configured slot count.")

    @staticmethod
    def url(slot):
        return f"https://app.aboardhr-wt{slot}.localhost"

    @staticmethod
    def environment():
        # A command launched from another worktree must not inherit its DB/shell identity.
        prefixes = ("DEVENV_", "DIRENV_", "PG", "POSTGRES_", "REDIS")
        excluded = {"DATABASE_URL", "RAILS_ENV", "RACK_ENV", "HTTP_HOST", "CANONICAL_HOST",
                    "PORT", "OVERMIND_PORT", "NGROK_HOST", "IN_NIX_SHELL",
                    "BUNDLE_GEMFILE", "BUNDLE_PATH", "BUNDLE_APP_CONFIG", "GEM_HOME", "GEM_PATH", "RUBYLIB"}
        return {key: value for key, value in os.environ.items()
                if not key.startswith(prefixes) and key not in excluded}

    def devenv(self, path, *args, **kwargs):
        return run("devenv", *args, cwd=path, env=self.environment(), **kwargs)

    def shell_command(self, path, *args):
        return run("direnv", "exec", path, *args, cwd=path, env=self.environment())

    def create(self, name, branch=None, base="origin/main", no_open=False):
        path = self.path(name)
        with self.lock():
            if path.exists() or path in self.worktrees():
                raise WorkspaceError(f"{path} already exists; use 'aboard-wt open {name}'.")
            if not (self.repo / ".env.development").is_file():
                raise WorkspaceError(f"Missing {self.repo / '.env.development'}")
            # Fetch before resolving refs, never during completion.
            remote = (branch or base).removeprefix("refs/remotes/").partition("/")[0]
            if remote not in self.git("remote").stdout.splitlines():
                remote = "origin"
            run("git", "-C", self.repo, "fetch", "--prune", remote)
            args = self.checkout_args(path, name, branch, base)
            slot = self.allocate_slot()
            self.root.mkdir(exist_ok=True)
            run("git", "-C", self.repo, "worktree", "add", *args)
            self.write_config(path, slot)
            shutil.copyfile(self.repo / ".env.development", path / ".env.development")
            (path / ".env.development").chmod(0o600)
            # Holds the private gem source credentials (e.g. packager.dev for Avo).
            if (self.repo / ".bundle" / "config").is_file():
                (path / ".bundle").mkdir(exist_ok=True)
                shutil.copyfile(self.repo / ".bundle" / "config", path / ".bundle" / "config")
                (path / ".bundle" / "config").chmod(0o600)
        print(f"Workspace: {path}\nURL: {self.url(slot)}", flush=True)
        print(f"If setup fails, retry with: aboard-wt setup {name}", flush=True)
        self.setup(name)
        if not no_open:
            self.open(name)

    def checkout_args(self, path, name, branch, base):
        if branch:
            local = branch.removeprefix("refs/heads/")
            if self.git("show-ref", "--verify", "--quiet", f"refs/heads/{local}", check=False).returncode == 0:
                checked_out = next((p for p, fields in self.worktrees().items()
                                    if fields.get("branch") == f"refs/heads/{local}"), None)
                if checked_out:
                    raise WorkspaceError(f"Branch {local} is already checked out at {checked_out}")
                return [str(path), local]
            remote = branch.removeprefix("refs/remotes/")
            if self.git("show-ref", "--verify", "--quiet", f"refs/remotes/{remote}", check=False).returncode:
                raise WorkspaceError(f"Unknown local or remote branch: {branch}")
            local = remote.partition("/")[2]
            if self.git("show-ref", "--verify", "--quiet", f"refs/heads/{local}", check=False).returncode == 0:
                raise WorkspaceError(f"Local branch {local} already exists; select it explicitly with --branch {local}.")
            return ["--track", "-b", local, str(path), remote]
        if self.git("check-ref-format", "--branch", name, check=False).returncode:
            raise WorkspaceError(f"Invalid branch name: {name}")
        if self.git("show-ref", "--verify", "--quiet", f"refs/heads/{name}", check=False).returncode == 0:
            raise WorkspaceError(f"Branch {name} already exists; use --branch {name}.")
        commit = self.git("rev-parse", "--verify", "--end-of-options", f"{base}^{{commit}}").stdout.strip()
        return ["-b", name, str(path), commit]

    def write_config(self, path, slot):
        web, redis = 3000 + slot, 6379 + slot
        (path / "devenv.local.nix").write_text(f'''# Generated by aboard-wt. {self.url(slot)}
{{ lib, config, ... }}:
{{
  services.postgres.listen_addresses = lib.mkForce "";
  services.redis.port = lib.mkForce {redis};
  services.redis.bind = "127.0.0.1";

  env = {{
    PORT = lib.mkForce "{web}";
    OVERMIND_PORT = lib.mkForce "{web}";
    POSTGRES_HOST = lib.mkForce config.env.PGHOST;
    POSTGRES_USER = lib.mkForce "";
    POSTGRES_PASSWORD = lib.mkForce "";
    POSTGRES_DATABASE_PREFIX = lib.mkForce "aboard";
    POSTGRES_DATABASE_DEVELOPMENT = lib.mkForce "aboard_development";
    POSTGRES_DATABASE_TEST = lib.mkForce "aboard_test";
    REDIS_URL = lib.mkForce "redis://127.0.0.1:{redis}/0";
    HTTP_HOST = lib.mkForce "aboardhr-wt{slot}.localhost";
    CANONICAL_HOST = lib.mkForce "aboardhr-wt{slot}.localhost";
    NGROK_HOST = lib.mkForce "";
    USE_SSL = lib.mkForce "1";
  }};

  processes = {{
    web = {{
      exec = "bundle exec falcon serve --count 1 -b http://127.0.0.1:{web}";
      after = [ "devenv:processes:postgres" "devenv:processes:redis" ];
    }};
    sidekiq = {{
      exec = "bundle exec sidekiq";
      after = [ "devenv:processes:postgres" "devenv:processes:redis" ];
    }};
    js.exec = "npm run build:watch";
    css.exec = "npm run build:css:watch";
  }};
}}
''')

    def setup(self, name):
        path = self.existing(name)
        with self.lock("workspace-" + name):
            marker = path / ".devenv/aboard-wt-prepared"
            if marker.exists():
                print("Already prepared; leaving databases unchanged.")
                return
            if self.running(path):
                raise WorkspaceError("Stop the workspace before preparing its databases.")
            run("direnv", "allow", path, env=self.environment())
            self.shell_command(path, "bash", "-c", "bundle check || bundle install")
            self.shell_command(path, "npm", "ci" if (path / "package-lock.json").exists() else "install")
            try:
                self.devenv(path, "up", "-d", "--strict-ports", "postgres", "redis")
                self.devenv(path, "processes", "wait", "--timeout", "120")
                self.shell_command(path, "env", "RAILS_ENV=development", "bin/rails", "db:prepare")
                self.shell_command(path, "env", "RAILS_ENV=test", "bin/rails", "db:prepare")
                seeded = path / ".devenv/aboard-wt-seeded"
                if not seeded.exists():
                    self.shell_command(path, "env", "RAILS_ENV=development", "bin/rails", "dev:prime")
                    seeded.touch()
            finally:
                self.devenv(path, "processes", "down")
            marker.touch()
        print(f"Ready: {self.url(self.config_slot(path))}")
        print("Demo login: admin@teamtailor.com (any code). Mail uses the main checkout's mailcatcher.")

    @staticmethod
    def running(path):
        pid_file = path / ".devenv/run/processes/native-manager.pid"
        try:
            pid = int(pid_file.read_text().strip())
            if pid <= 0:
                return False
            os.kill(pid, 0)
            return True
        except (OSError, ValueError):
            return False

    def up(self, name):
        path = self.existing(name)
        if not (path / ".devenv/aboard-wt-prepared").exists():
            raise WorkspaceError(f"Run 'aboard-wt setup {name}' first.")
        with self.lock("workspace-" + name):
            if self.running(path):
                raise WorkspaceError("This workspace is already running. Use window 2 or 'devenv processes attach'.")
            slot = self.config_slot(path)
            if any(self.port_busy(port) for port in (3000 + slot, 6379 + slot)):
                raise WorkspaceError("A workspace port is already in use; refusing to start on a different port.")
            self.devenv(path, "up", "--strict-ports")

    def stop(self, name):
        path = self.existing(name)
        # Do not take the up lock: the foreground supervisor holds it while running.
        if self.running(path):
            self.devenv(path, "processes", "down")
        else:
            with self.lock("workspace-" + name):
                pass
        print(f"Stopped {name}; code and databases preserved.")

    def pane(self, name, kind, argv=()):
        path = self.existing(name)
        if kind == "exec":
            command = list(argv[1:] if argv[:1] == ["--"] else argv)
            if not command:
                raise WorkspaceError("Give a command to run: aboard-wt _pane NAME exec -- COMMAND...")
        else:
            command = shlex.split(os.environ.get("EDITOR", "nvim")) if kind == "editor" else [
                os.environ.get("SHELL", "/bin/bash"), "-i"
            ]
        os.chdir(path)
        os.execvpe("direnv", ["direnv", "exec", str(path), *command], self.environment())

    def open(self, name):
        path = self.existing(name)
        session = f"aboard-{name}"
        target = f"={session}"
        with self.lock("tmux-" + name):
            if run("tmux", "has-session", "-t", target, capture=True, check=False).returncode == 0:
                owner = run("tmux", "show-option", "-qv", "-t", session, "@aboard-wt-path", capture=True).stdout.strip()
                if owner != str(path):
                    raise WorkspaceError(f"Session {session} already exists and is not managed by aboard-wt.")
            else:
                if not (path / ".devenv/aboard-wt-prepared").exists():
                    raise WorkspaceError(f"Run 'aboard-wt setup {name}' first.")
                run("direnv", "allow", path, env=self.environment())
                executable = os.environ.get("ABOARD_WT_EXE", "aboard-wt")
                editor = shlex.join([executable, "_pane", name, "editor"])
                interactive = shlex.join([executable, "_pane", name, "shell"])
                supervisor = shlex.join([executable, "up", name])
                server = f"{supervisor}; exec {interactive}"
                editor_id = run("tmux", "new-session", "-d", "-P", "-F", "#{window_index}",
                                "-s", session, "-n", "editor", "-c", path,
                                "-x", "200", "-y", "50", editor, capture=True).stdout.strip()
                run("tmux", "set-option", "-t", session, "@aboard-wt-path", path)
                # Explicit indexes give the same shortcuts even with a different global base-index.
                if editor_id != "1":
                    run("tmux", "move-window", "-s", target + ":editor", "-t", target + ":1")
                run("tmux", "new-window", "-t", target + ":2", "-n", "dev", "-c", path, interactive)
                run("tmux", "split-window", "-h", "-l", "50%", "-t", target + ":2", "-c", path, server)
                run("tmux", "select-pane", "-t", target + ":2.{left}")
                run("tmux", "select-window", "-t", target + ":1")
                run("tmux", "set-option", "-t", session, "status-right", self.url(self.config_slot(path)))
        if os.environ.get("TMUX"):
            run("tmux", "switch-client", "-t", target)
        else:
            run("tmux", "attach-session", "-t", target)

    def list(self):
        print(f"{'NAME':24} {'BRANCH':36} {'STATUS':12} URL")
        records = self.worktrees()
        for name in self.names():
            path = self.path(name)
            branch = records[path].get("branch", "detached").removeprefix("refs/heads/")
            status = "running" if self.running(path) else "stopped"
            if not (path / ".devenv/aboard-wt-prepared").exists():
                status = "needs setup"
            print(f"{name:24} {branch:36} {status:12} {self.url(self.config_slot(path))}")

    def remove(self, name):
        path = self.existing(name)
        if self.git("-C", str(path), "status", "--porcelain").stdout.strip():
            raise WorkspaceError("Workspace has uncommitted changes; commit or move them before removing it.")
        if self.git("-C", str(path), "log", "--oneline", "HEAD", "--not", "--remotes").stdout.strip():
            raise WorkspaceError("Workspace has commits not present on a remote; push them before removing it.")
        if not sys.stdin.isatty() or input(f"Delete {path} and ALL its databases/uploads? Type '{name}' to confirm: ") != name:
            raise WorkspaceError("Removal cancelled.")
        self.stop(name)
        with self.lock(), self.lock("workspace-" + name), self.lock("tmux-" + name):
            target = f"=aboard-{name}"
            owner = run("tmux", "show-option", "-qv", "-t", f"aboard-{name}", "@aboard-wt-path",
                        capture=True, check=False).stdout.strip()
            if owner == str(path):
                run("tmux", "kill-session", "-t", target)
            run("git", "-C", self.repo, "worktree", "remove", path)
        print("Workspace removed. Branch retained.")


def main():
    parser = argparse.ArgumentParser(prog="aboard-wt", description="Personal isolated Aboard worktrees and tmux sessions.")
    commands = parser.add_subparsers(dest="command", required=True)
    create = commands.add_parser("create", help="Create and seed a workspace, then open tmux")
    create.add_argument("name")
    create.add_argument("--branch", help="Existing local or remote-tracking branch")
    create.add_argument("--base", default="origin/main", help="Base for a new branch (default: origin/main)")
    create.add_argument("--no-open", action="store_true", help="Prepare without opening tmux")
    commands.add_parser("list", help="List workspaces, branches, status, and URLs")
    for command, help_text in (("open", "Open or switch to the two-window tmux session"),
                               ("setup", "Prepare a workspace after interrupted creation"),
                               ("up", "Run the full stack in the foreground"),
                               ("stop", "Stop services, preserving all data"),
                               ("remove", "Confirm deletion of a clean, pushed workspace")):
        commands.add_parser(command, help=help_text).add_argument("name")
    completion = commands.add_parser("_complete", help="Print cached shell completion candidates")
    completion.add_argument("kind", choices=("branches", "workspaces"))
    pane = commands.add_parser("_pane", help="Internal: enter a worktree's editor or shell, or run a command in it")
    pane.add_argument("name")
    pane.add_argument("kind", choices=("editor", "shell", "exec"))
    pane.add_argument("argv", nargs=argparse.REMAINDER)
    args = vars(parser.parse_args())
    command = args.pop("command")
    try:
        workspaces = Workspaces()
        if command == "_complete":
            print("\n".join(workspaces.branches() if args["kind"] == "branches" else workspaces.names()))
        else:
            getattr(workspaces, command.removeprefix("_"))(**args)
    except (WorkspaceError, OSError, subprocess.CalledProcessError) as error:
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr.strip(), file=sys.stderr)
        print(f"aboard-wt: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130
    return 0


if __name__ == "__main__":
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)
    sys.exit(main())
